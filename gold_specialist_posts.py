def choose_topic(now):
    """Stable daily selection; repeated runs on one date choose same topic."""
    date_key = now.strftime("%Y-%m-%d")
    digest = hashlib.sha256(date_key.encode("utf-8")).hexdigest()
    index = int(digest[:12], 16) % len(TOPICS)
    return TOPICS[index], index


def build_post(topic, now):
    date = now.strftime("%Y/%m/%d")
    paragraphs = topic["body"].split("\n\n")

    lines = [
        "🟡 <b>فاندبورد طلا | آموزش و تحلیل</b>",
        "",
        f"📌 <b>{escape(topic['title'])}</b>",
        "",
    ]

    for paragraph in paragraphs:
        lines.append(escape(paragraph))
        lines.append("")

    lines.extend([
        f"💬 <b>سؤال امروز:</b> {escape(topic['question'])}",
        "",
        f"📚 دسته‌بندی: {escape(topic['category'])}",
        f"🗓 تاریخ تولید پیش‌نویس: {date}",
        "",
        "<i>این مطلب آموزشی است و توصیه خرید یا فروش محسوب نمی‌شود.</i>",
    ])

    return "\n".join(lines)


